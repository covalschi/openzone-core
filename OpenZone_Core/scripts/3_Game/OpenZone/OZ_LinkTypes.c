// Прив'язка акаунта Discord -- у ЯДРІ, а не в КПК.
//
// Прив'язка належить ГРАВЦЕВІ, а не пристрою. Вона переживає втрату КПК,
// смерть і зміну апарата, і від неї залежить усе, що читає ролі Discord:
// фракція, стаж, посади, мітки. Тримати її в моді інтерфейсу означало б, що
// сервер без КПК не може прив'язати нікого -- а рації, квестам і ІІ фракція
// потрібна так само, і екран їм ні до чого.
//
// Тому й окрема пара RPC, а не сторінка реєстру: сторінки проходять крізь
// OZ_PageAccess, який КПК підміняє власною перевіркою «чи є ця сторінка на
// цьому пристрої». Прив'язка через сторінку означала б, що прив'язатись може
// лише той, у кого вже є КПК із потрібною сторінкою в профілі -- тобто рівно
// те, чого ми уникаємо.

class OZ_LinkAsk
{
    string Uid = "";
}

// Що видав міст: КОРОТКИЙ КОД для команди /link у Discord.
//
// Не посилання OAuth. Двісті символів адреси, які людина переписує очима з
// ігрового екрана в браузер, -- найгірша частина будь-якого потоку, де вона
// зустрічається. Шість символів у чат Discord -- ні.
class OZ_LinkGrant
{
    string Code         = "";
    int    ExpiresInSec = 0;
}

class OZ_LinkState
{
    bool   Linked      = false;
    string DiscordId   = "";
    string DiscordName = "";
}

