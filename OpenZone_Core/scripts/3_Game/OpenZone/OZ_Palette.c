// джерелом токенів (dayz-mcp.toml -> ui/tokens.json). Клас нічого не робить
// і нічого не важить: це та сама таблиця, тільки написана один раз.
//
// ЯК ТРИМАТИ СИНХРОННИМ. Значення -- це $color.* із ui/tokens.json,
