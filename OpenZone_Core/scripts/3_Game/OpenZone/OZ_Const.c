// Константи, спільні для всього фреймворку.
//
// Шляхи в $profile: пишемо з екранованим зворотним слешем. Пряма коса теж
// працює (ваніль так і робить у CameraTools), але змішувати два стилі в одному
// проєкті -- шукати собі проблем на рівному місці.

class OZ_Const
{
    // Ім'я мода для CF RPCManager. Разом з іменем функції утворює ключ, тому
    // зіткнення з чужим модом можливе лише при збігу ОБОХ рядків.
    static const string MOD        = "OpenZone";
    static const string LOG_PREFIX = "[OpenZone] ";

    static const string PROFILE_DIR = "$profile:OpenZone";
    static const string BACKUP_DIR  = "$profile:OpenZone\\Backup";
    static const string PLAYERS_DIR = "$profile:OpenZone\\players";
    static const string LANG_DIR    = "$profile:OpenZone\\Lang";
    static const string SETTINGS    = "$profile:OpenZone\\OZ_Core_Settings.json";

    // ТЕГ цього файла для конфіг-служби -- КОНСТАНТОЮ, а не рядком у кожному
    // виклику. З тега робиться ім'я резервної копії (OZ_Json.Backup пише
    // <тег>.bak.json), і два написання одного тега -- "Settings" при
    // завантаженні й "settings" при записі дзеркал -- на Windows дають той
    // самий файл, а на Linux два різні: адмін, що шукає копію після збою,
    // знайшов би не ту.
    static const string SETTINGS_TAG = "Settings";

    // Версія схеми Settings.json. Зростає лише разом із міграцією.
    //
    // v3 (2026-09-01, ТЗ-2 R3.1): дзеркала Discord по родах. Порожній список
    // означає «всі вимкнені» -- це свідома зміна поведінки, а не збереження
    // старої, і саме тому версія піднялась.
    static const int SCHEMA_SETTINGS = 3;

    // PAGE_ADMIN ТУТ БІЛЬШЕ НЕМАЄ, і це не перейменування, а знята межа.
    //
    // Адмінська консоль була сторінкою в спільному реєстрі, i щоб її
    // пропустити, гейт КПК тримав виняток першим рядком -- єдиний виняток на
    // всю межу безпеки. Рішення власника 2026-09-01: «КПК взагалі не повинен
    // мати адмінських функцій, усі адмінські функції у VPP». Розділи поїхали
    // у власний реєстр (OZ_AdminRegistry) i власний конверт (OZ_AdminReq), а
    // в гейта лишилось одне правило без винятків: сторінка вимагає приладу.

    // СКІЛЬКИ РУШІЙ НАСПРАВДІ ЧЕКАЄ асинхронну відповідь -- зміряно, а не
    // задокументовано.
    //
    // Тут стояли межі 3..120, у які клампувався Bridge.PollTimeoutSec, а той
    // ішов у RestApi.SetOption. Обидва виклики рушій ігнорує: асинхронний
    // запит помирає рівно на десятій секунді, хоч би що в них стояло (той
    // самий стенд, і diag-, і релізний сервер, 1.29). Настройка й межі до
    // неї описували діапазон, якого не існує; справжня стеля задається на
    // боці моста -- POLL_HOLD_SECONDS мусить бути МЕНШИЙ за це число.
    static const int REST_TIMEOUT_SEC = 10;

    // Відповідь буде, але пізніше й не звідси. Сторінка каже це замість
    // ключа помилки, і диспетчер тоді мовчить: інакше клієнт побачив би
    // «не вдалося» за секунду до того, як приїде справжня відповідь.
    static const string DEFER = "@defer";

    // Рядок у рушійному RPC живе в буфері ~1024 байти: 1011 байт корисного
    // JSON проходили, 1386 приїздили як "String CORRUPTED" (зміряно на
    // стенді, список нотаток). Довші за поріг тіла їдуть частинами
    // OZ_ReqPart/OZ_ResPart попереду свого конверта; приймач приклеює їх
    // перед тілом фінального. Порядок гарантує канал guaranteed-RPC.
    static const int RPC_STR_CHUNK = 900;

    // СТЕЛЯ ТІЛА НОВИНИ, В БАЙТАХ, І ВОНА ОДНА НА ВСІ ПОВЕРХНІ.
    //
    // Тут, у 3_Game, саме тому, що читачів троє й у різних модах: консоль VPP
    // (5_Mission), розділ новин ядра (4_World) і кламп Tuning у КПК
    // (OpenZone_PDA, теж 3_Game). Кожен зі своїм числом -- це рівно
    // розбіжність 96: тіло на тисячу байтів консоль відхиляла, а сторінка
    // КПК приймала, і в КПК стеля була ще й правна адміном.
    //
    // Тисяча -- запас у два десятки байтів до рушійної межі: JsonFileLoader
    // мовчки ріже будь-яке строкове значення JSON на 1023 байтах (зміряно,
    // persistence-networking.md:520-522), а тіло переходить межу гри одним
    // таким значенням.
    //
    // ГРА ЛИШЕ ЧЕМНА: судить МІСТ (openzone-bridge/src/news.js, BODY_MAX --
    // та сама тисяча). Він відмовляє словом body_too_long і возить у відмові
    // своє число, тож поверхня каже застосовану межу, а не власну.
    static const int NEWS_BODY_MAX = 1000;
}

