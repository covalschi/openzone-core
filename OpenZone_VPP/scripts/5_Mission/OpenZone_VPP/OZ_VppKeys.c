// Замок гарячих клавіш VPP на час, поки відкрите вікно OpenZone.
//
// НАВІЩО. У VPP на Backspace стоїть UAToggleFreeCam (modded_inputs.xml,
// preset). Поки в КПК набираєш ім'я частоти, Backspace не стирає літеру, а
// кидає в вільну камеру. І це не одна клавіша: тим самим шляхом ідуть H
// (телепорт у приціл), Delete (знести об'єкт у прицілі), K (полагодити
// техніку), P, Y, J -- усього шістнадцять прив'язок.
//
// ЧОМУ НЕ AddActiveInputExcludes. Меню вже кличе його з групою "menu", і це
// не допомагає: група "menu" перелічена у ванільному inputs.xml і містить
// ванільні входи. VPP до неї нічого не додає -- єдина його група виключень
// зветься VPPCamControls і тримає рух камери, а не сам перемикач.
//
// ЧОМУ НЕ SupressNextFrame. Він глушить УСЕ, зокрема наш власний PTT, і
// глушить сліпо -- щокадру, поки вікно живе.
//
// ЯК ТРЕБА. VPP має для цього власний вимикач і сам ним користується:
// LockPlayerControl() ставить SetKeybindsStatus(true), коли відкривається
// вікно самого VPP. Шістнадцять його прив'язок питають GetKeybindsStatus()
// першим рядком. Отже ми просто кажемо те саме, що сказав би VPP.
//
// Своя перевірка в VPP теж є -- IsTyping(), -- але вона дивиться на віджет
// ПІД КУРСОРОМ, а не на фокус. Клацнув у поле, відвів мишу до списку, набираєш
// -- курсор уже не над полем, і VPP вважає, що ніхто не друкує. Саме так це й
// ловиться в КПК.
//
// Знання про VPP лишається ТУТ, у pbo, який без VPP не вантажиться. Ні ядро,
// ні КПК, ні рація про цей файл не знають.

